"""User watchlist parsers. Every input is a small hand-written string; nothing is run or installed."""

from __future__ import annotations

import json

import pytest

from hunter.inventory import Component
from hunter.inventory.parsers import FORMATS, FormatError, detect_format, parse
from hunter.inventory.purl import parse_purl

SHA = "0123456789abcdef0123456789abcdef01234567"


def _found(result) -> set[tuple]:
    return {(item.ecosystem, item.name, item.version, item.direct) for item in result.components}


# --- npm lockfiles ------------------------------------------------------------

NPM_V3 = json.dumps(
    {
        "name": "app",
        "lockfileVersion": 3,
        "packages": {
            "": {"name": "app", "dependencies": {"left-pad": "^1.0.0"}, "devDependencies": {"@scope/tool": "2.0.0"}},
            "node_modules/left-pad": {"version": "1.3.0"},
            "node_modules/@scope/tool": {"version": "2.0.0"},
            "node_modules/left-pad/node_modules/@s/b": {"version": "0.4.1"},
            "node_modules/linked": {"resolved": "packages/linked", "link": True},
            "packages/linked": {"name": "linked", "version": "0.0.1"},
            "node_modules/alias-name": {"name": "real-name", "version": "3.1.0"},
        },
    }
)

NPM_V1 = json.dumps(
    {
        "lockfileVersion": 1,
        "dependencies": {
            "a": {"version": "1.0.0", "dependencies": {"b": {"version": "2.0.0", "dependencies": {"c": {"version": "3.0.0"}}}}},
            "local": {"version": "file:../local"},
        },
    }
)


def test_npm_lock_v3_nested_scoped_links_and_direct_flags():
    result = parse(NPM_V3, "package-lock.json")
    assert result.format == "npm-lock"
    assert _found(result) == {
        ("npm", "left-pad", "1.3.0", 1),
        ("npm", "@scope/tool", "2.0.0", 1),
        ("npm", "@s/b", "0.4.1", 0),
        ("npm", "real-name", "3.1.0", 0),
    }
    # The link entry and the workspace folder are skipped, not guessed.
    assert result.skipped == 2


def test_npm_lock_v1_walks_the_nested_tree():
    result = parse(NPM_V1)
    assert _found(result) == {("npm", "a", "1.0.0", None), ("npm", "b", "2.0.0", None), ("npm", "c", "3.0.0", None)}
    assert result.skipped == 1


