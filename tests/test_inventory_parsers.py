# --- detection ----------------------------------------------------------------


@pytest.mark.parametrize(
    "text, fmt",
    [
        (NPM_V3, "npm-lock"),
        (NPM_V1, "npm-lock"),
        (YARN_CLASSIC, "yarn-lock"),
        (YARN_BERRY, "yarn-lock"),
        (PNPM_V5, "pnpm-lock"),
        (PNPM_V6, "pnpm-lock"),
        (PNPM_V9, "pnpm-lock"),
        (PACKAGE_JSON, "package-json"),
        (REQUIREMENTS, "requirements"),
        (POETRY_LOCK, "toml-lock"),
        (UV_LOCK, "toml-lock"),
        (PIPFILE_LOCK, "pipfile-lock"),
        (CYCLONEDX, "cyclonedx"),
        (SPDX, "spdx"),
        (PLAIN, "plain"),
        (WORKFLOW, "workflow"),
    ],
)
def test_detect_format_reads_content_not_the_name(text, fmt):
    assert detect_format(text, "misleading-name.bin") == fmt


def test_unknown_text_is_not_guessed():
    assert detect_format("Dear reader, this is a letter.\nIt lists nothing.") is None
    assert detect_format(json.dumps({"unrelated": True})) is None
    with pytest.raises(FormatError):
        parse("Dear reader, this is a letter.")


def test_filename_breaks_a_tie_only_when_content_says_nothing():
    assert detect_format("# only comments\n", "requirements.txt") == "requirements"
    assert detect_format("runs:\n  using: node20\n", "action.yml") == "workflow"
    assert detect_format("{}", "package.json") == "package-json"


def test_forced_format_that_does_not_fit_raises_without_file_text():
    with pytest.raises(FormatError) as err:
        parse("secret-ish text that is not json", fmt="npm-lock")
    assert "secret-ish" not in str(err.value)
    assert set(FORMATS) >= {"npm-lock", "plain", "workflow"}
