def test_spdx_purls_in_external_refs():
    result = parse(SPDX, "sbom.spdx.json")
    assert result.format == "spdx"
    assert _found(result) == {("npm", "left-pad", "1.3.0", None), ("openvsx", "pub.my-ext", "1.2.0", None)}
    assert result.skipped == 1


def test_purl_forms():
    assert parse_purl("pkg:npm/%40scope/name@1.0.0") == Component("npm", "@scope/name", "1.0.0")
    assert parse_purl("pkg:npm/@scope/name@1.0.0") == Component("npm", "@scope/name", "1.0.0")
    assert parse_purl("pkg:pypi/Foo_Bar@1.0") == Component("pypi", "foo-bar", "1.0")
    assert parse_purl("pkg:github/Owner/Repo@" + SHA) == Component("github-actions", "owner/repo", SHA)
    assert parse_purl("pkg:githubactions/o/r/sub/path@v1") == Component("github-actions", "o/r", "v1")
    assert parse_purl("pkg:golang/github.com/gorilla/mux@v1.8.0") is None
    assert parse_purl("not a purl") is None


